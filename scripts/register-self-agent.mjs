// Registers the Launchmate agent with Self Agent ID on Celo MAINNET (wallet-free mode).
//
//   npm run self:register              -> full registration (you scan a QR with the Self app)
//   npm run self:register -- --check   -> opens a session and prints the QR, registers NOTHING
//
// What happens: Self generates the agent's EVM key server-side. You scan the QR with the Self
// app using your REAL passport. When it completes we export the key, VERIFY it matches the
// registered address, and save it to .env.local. The private key is never printed.
//
// Mainnet = real passports only (a mock passport fails). Use the SAME disclosures if you ever
// refresh or deregister: minimumAge 0, ofac false.
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { execFile } from "node:child_process";
import { createPublicClient, http, isAddress } from "viem";
import { celo } from "viem/chains";
import { privateKeyToAccount } from "viem/accounts";
import { getAgentInfo, requestRegistration, verifyAgent } from "@selfxyz/agent-sdk";

const ENV = ".env.local";
const NETWORK = "mainnet";
const DISCLOSURES = { minimumAge: 0, ofac: false }; // verification config 0
const check = process.argv.includes("--check");

const read = () => (existsSync(ENV) ? readFileSync(ENV, "utf8") : "");
const has = (name) => new RegExp(`^${name}=.+`, "m").test(read());
const get = (name) => read().match(new RegExp(`^${name}=(.+)$`, "m"))?.[1]?.trim();
const fail = (m) => { console.error(m); process.exit(1); };

// ── Guards ───────────────────────────────────────────────────────────────────────────────
if (!check && has("SELF_AGENT_ID")) {
  fail(`Refusing: ${ENV} already has SELF_AGENT_ID. Registering again would use up one of your 10 mainnet agent slots.`);
}

// An earlier (unfunded) wallet may exist from wallet:generate. Only supersede it if it is provably empty.
let supersede = false;
if (!check && has("AGENT_PRIVATE_KEY")) {
  const key = get("AGENT_PRIVATE_KEY");
  const addr = privateKeyToAccount(key).address;
  const client = createPublicClient({ chain: celo, transport: http("https://forno.celo.org") });
  const [balance, nonce] = await Promise.all([client.getBalance({ address: addr }), client.getTransactionCount({ address: addr })]);
  if (balance !== 0n || nonce !== 0) {
    fail(`Refusing: the existing AGENT_PRIVATE_KEY (${addr}) has funds or history on Celo mainnet. Move them first; I will not overwrite a used key.`);
  }
  supersede = true;
  console.log(`Existing AGENT_PRIVATE_KEY (${addr}) is empty on mainnet, so it will be set aside (renamed, not deleted).`);
}

// ── Start the session ────────────────────────────────────────────────────────────────────
const session = await requestRegistration({ mode: "wallet-free", network: NETWORK, disclosures: DISCLOSURES });
console.log("\nSelf registration session opened (Celo mainnet, wallet-free).");
console.log(`  Agent address (generated by Self): ${session.agentAddress}`);
console.log(`  Session expires in ~${Math.round(session.timeRemainingMs / 60000)} min`);
console.log("\nSteps:");
for (const line of session.humanInstructions ?? []) console.log("  - " + line);
console.log(`\nQR code image (open it on this computer, scan with the Self app on your phone):\n  ${session.scanUrl}`);
console.log(`\nOr open this link on your phone:\n  ${session.deepLink}\n`);
if (!check && process.platform === "win32") execFile("cmd", ["/c", "start", "", session.scanUrl], () => {});

if (check) {
  console.log("--check: session created OK. Nothing was registered (no one scanned). It will simply expire.");
  // Let open network handles drain before exiting (avoids a harmless libuv assertion on Windows).
  await new Promise((r) => setTimeout(r, 300));
  process.exit(0);
}

// ── Wait for the scan, then export + verify + save the key ───────────────────────────────
console.log("Waiting for you to scan with the Self app… (Ctrl+C to cancel; nothing is registered until you scan)");
const result = await session.waitForCompletion({ timeoutMs: 25 * 60 * 1000 });
console.log(`\nRegistered on-chain. agentId = ${result.agentId}`);

const privateKey = await session.exportKey();
const derived = privateKeyToAccount(privateKey).address;
if (derived.toLowerCase() !== result.agentAddress.toLowerCase()) {
  // Do not save a key that does not match the registered address.
  fail(`The exported key does not match the registered address (${derived} vs ${result.agentAddress}). Not saving. Export is available for ~30 minutes: re-run is NOT safe, contact support.`);
}

// Save immediately, before anything else can go wrong.
let env = read();
if (supersede) {
  env = env
    .replace(/^AGENT_PRIVATE_KEY=/m, "OLD_UNFUNDED_AGENT_PRIVATE_KEY=")
    .replace(/^AGENT_WALLET_ADDRESS=/m, "OLD_UNFUNDED_AGENT_WALLET_ADDRESS=");
  writeFileSync(ENV, env);
}
const prefix = read() && !read().endsWith("\n") ? "\n" : "";
appendFileSync(ENV, `${prefix}AGENT_PRIVATE_KEY=${privateKey}\nAGENT_WALLET_ADDRESS=${derived}\nSELF_AGENT_ID=${result.agentId}\n`, { mode: 0o600 });
console.log(`Saved AGENT_PRIVATE_KEY, AGENT_WALLET_ADDRESS, SELF_AGENT_ID to ${ENV} (private key not printed).`);

// ── Independent on-chain verification ────────────────────────────────────────────────────
const pad = "0x" + derived.slice(2).toLowerCase().padStart(64, "0");
const onchain = await verifyAgent(pad, { network: NETWORK });
const info = await getAgentInfo(result.agentId, { network: NETWORK }).catch(() => undefined);
console.log("\nOn-chain check (Self registry, Celo mainnet):");
console.log("  verifyAgent():", JSON.stringify(onchain, (_k, v) => (typeof v === "bigint" ? v.toString() : v)));
if (info) console.log(`  getAgentInfo(): isVerified=${info.isVerified} proofExpiresAt=${info.proofExpiresAt} provider=${info.proofProvider}`);
console.log("\nPublic details to share/record:");
console.log(`  Self agentId : ${result.agentId}`);
console.log(`  Agent wallet : ${derived}`);
console.log("\nNext: back up AGENT_PRIVATE_KEY in a password manager. Do NOT share it. Then fund this address (not the old one).");
if (!isAddress(derived)) process.exit(1);
